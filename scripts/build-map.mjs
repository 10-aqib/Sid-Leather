// Generates src/lib/map-data.ts from Natural Earth (world-atlas 110m).
// Equirectangular projection, cropped to Europe + Asia.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const countries = feature(topo, topo.objects.countries).features;

const LON0 = -25, LON1 = 150, LAT0 = 70, LAT1 = -12;
const W = 1000;
const K = W / (LON1 - LON0);
const H = Math.round((LAT0 - LAT1) * K);
const px = (lon, lat) => [Math.round((lon - LON0) * K), Math.round((LAT0 - lat) * K)];

// Markets named on the existing SID Leather website (Asia) + origin.
const ASIA = new Set(["Vietnam", "Taiwan", "Thailand", "Cambodia", "China", "South Korea", "Indonesia"]);
const ORIGIN = "Pakistan";
const EUROPE_IDS = new Set(); // filled by continent heuristic below

function ringToPath(ring) {
  const pts = [];
  for (const [lon, lat] of ring) {
    const p = px(lon, lat).join(" ");
    if (p !== pts[pts.length - 1]) pts.push(p);
  }
  if (pts.length < 3) return "";
  return "M" + pts.join("L") + "Z";
}
function geomPath(g) {
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  return polys
    .filter((poly) => poly[0].some(([lon, lat]) => lon > LON0 - 5 && lon < LON1 + 5 && lat < LAT0 + 5 && lat > LAT1 - 5))
    .map((poly) => poly.map(ringToPath).join(""))
    .join("");
}
// Rough European bounding test on the country centroid (lon -25..40, lat 35..71), excluding Asian/African states.
const notEurope = new Set(["Turkey", "Russia", "Kazakhstan", "Georgia", "Azerbaijan", "Armenia", "Syria", "Iraq", "Iran", "Israel", "Lebanon", "Jordan", "Cyprus", "N. Cyprus", "Morocco", "Algeria", "Tunisia", "Libya", "Egypt", "Palestine"]);
function centroid(g) {
  let sx = 0, sy = 0, n = 0;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  // Use the largest polygon's outer ring
  let best = polys[0];
  for (const p of polys) if (p[0].length > best[0].length) best = p;
  for (const [lon, lat] of best[0]) { sx += lon; sy += lat; n++; }
  return [sx / n, sy / n];
}

const out = { base: [], europe: [], asia: [], origin: "" };
for (const f of countries) {
  const name = f.properties.name;
  const d = geomPath(f.geometry);
  if (!d) continue;
  const [clon, clat] = centroid(f.geometry);
  if (name === ORIGIN) out.origin = d;
  else if (ASIA.has(name)) out.asia.push({ name, d });
  else if (!notEurope.has(name) && clon > -25 && clon < 40 && clat > 35 && clat < 71) { out.europe.push(d); EUROPE_IDS.add(name); }
  else out.base.push(d);
}

const point = (lon, lat) => px(lon, lat);
const markers = {
  karachi: point(67.01, 24.86),
  // Market label points (placed at each market's main commercial hub) and route endpoints.
  cities: [
    ["Vietnam", 106.63, 10.82],
    ["Taiwan", 121.56, 25.03],
    ["Thailand", 100.5, 13.76],
    ["Cambodia", 104.92, 11.56],
    ["China", 113.26, 23.13],
    ["Hong Kong", 114.17, 22.32],
    ["South Korea", 126.98, 37.57],
    ["Indonesia", 106.85, -6.21],
    ["Singapore", 103.82, 1.35],
  ].map(([name, lon, lat]) => ({ name, x: point(lon, lat)[0], y: point(lon, lat)[1] })),
  europe: point(10, 50),
};

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<path d="${out.base.join("")}" fill="#3a2a21"/>
<path d="${out.europe.join("")}" fill="#7d5a40"/>
${out.asia.map((a) => `<path d="${a.d}" fill="#a66e45"><title>${a.name}</title></path>`).join("\n")}
<path d="${out.origin}" fill="#d4b995"><title>Pakistan</title></path>
</svg>
`;
writeFileSync(new URL("../public/images/markets-map.svg", import.meta.url), svg);

const ts = `// Generated by scripts/build-map.mjs from Natural Earth 1:110m data (public domain). Do not edit by hand.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
export const karachi = ${JSON.stringify(markers.karachi)} as const;
export const europeCentre = ${JSON.stringify(markers.europe)} as const;
export const marketCities: { name: string; x: number; y: number }[] = ${JSON.stringify(markers.cities)};
`;
writeFileSync(new URL("../src/lib/map-data.ts", import.meta.url), ts);
console.log("map-data.ts written", { W, H, europe: [...EUROPE_IDS].length, asia: out.asia.map((a) => a.name) }, (svg.length / 1024).toFixed(1) + "KB svg");
